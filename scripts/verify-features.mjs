import assert from 'node:assert/strict'
import { runtime } from './testRuntime.mjs'

const env = runtime()
const life = env.read('src/lib/dataLifecycle.ts')
const task = { id: 'task-one', title: 'Recover this task', done: false }
env.values.set('nivra-tasks', '[]')
life.recordStorageChange('nivra-tasks', JSON.stringify([task]), '[]')
assert.equal(life.readTrash().length, 1)
life.restoreTrash(life.readTrash()[0].id)
assert.equal(JSON.parse(env.values.get('nivra-tasks'))[0].title, task.title)
assert.equal(life.readTrash().length, 0)
assert.ok(env.changes.includes('nivra-tasks'))

life.recordStorageChange('nivra-tasks', JSON.stringify([task]), '[]')
life.recordStorageChange('nivra-tasks', JSON.stringify([]), JSON.stringify([task]))
assert.equal(life.readTrash().length, 0, 'Undo must remove the redundant trash copy')
life.recordStorageChange('nivra-tasks', JSON.stringify([task]), '[]')
assert.throws(() => life.restoreTrash(life.readTrash()[0].id), /Ya existe/)
env.clock.now += life.RETENTION + 1
life.purgeExpiredTrash()
assert.equal(life.readTrash().length, 0)
assert.equal(JSON.parse(env.values.get(life.TRASH_KEY)).length, 0)

const before = { id: 'note-one', title: 'Original', body: 'Version one', folder: 'missing-folder', updated: 1 }
const after = { ...before, title: 'Renamed', body: 'Version two', updated: 2 }
env.values.set('nivra-vault', JSON.stringify([after]))
life.recordStorageChange('nivra-vault', JSON.stringify([before]), JSON.stringify([after]))
let versions = JSON.parse(env.values.get(life.VERSIONS_KEY))
assert.equal(versions[0].note.body, 'Version one')
life.restoreVersion(versions[0])
assert.equal(JSON.parse(env.values.get('nivra-vault'))[0].body, 'Version one')
assert.ok(JSON.parse(env.values.get(life.VERSIONS_KEY)).some(version => version.note.body === 'Version two'), 'Restore must preserve the current version')
for (let index = 0; index < 65; index++) { env.clock.now += 31000; life.saveVersion('nivra-vault', { ...before, body: `Checkpoint ${index}` }) }
assert.equal(JSON.parse(env.values.get(life.VERSIONS_KEY)).filter(version => version.noteId === before.id).length, 50)
env.values.set('nivra-vault', '[]')
life.recordStorageChange('nivra-vault', JSON.stringify([before]), '[]')
life.restoreTrash(life.readTrash()[0].id)
assert.equal(JSON.parse(env.values.get('nivra-vault'))[0].folder, undefined)

const share = env.read('src/lib/sharing.ts')
const note = { version: 1, kind: 'note', title: 'Galego e español ✦', body: '# Unha nota\n\n¿Que tal? <script>alert(1)</script>' }
const url = share.portableLink(note)
assert.ok(url.startsWith('http://localhost:5173/shared#'))
assert.equal(JSON.stringify(share.readPortable(new URL(url).hash)), JSON.stringify(note))
assert.throws(() => share.portableLink({ ...note, body: 'x'.repeat(25000) }), /demasiado larga/)
assert.throws(() => share.readPortable('#broken%%%'))
assert.throws(() => share.readPortable(`#${btoa(JSON.stringify({ version: 1, kind: 'script', title: '', body: '' }))}`), /no es válido/)
await assert.rejects(share.publishNote('one', 'Title', 'Body'), /Supabase está en pausa/)

const pin = env.read('src/lib/pin.ts')
assert.equal(pin.isUnlocked('app'), true)
await pin.configurePin('vault', '753951', '')
assert.equal(pin.isUnlocked('vault'), true)
assert.equal(env.values.get(pin.PIN_KEY).includes('753951'), false, 'The raw PIN must never be persisted')
pin.lockNow()
assert.equal(pin.isUnlocked('app'), true)
assert.equal(pin.isUnlocked('vault'), false)
assert.equal(await pin.verifyPin('111111'), false)
assert.equal(await pin.verifyPin('753951'), true)
await assert.rejects(pin.configurePin('off', '', '000000'), /no es correcto/)
await pin.configurePin('app', '951753', '753951')
pin.lockNow()
assert.equal(pin.isUnlocked('app'), false)
assert.equal(pin.isUnlocked('vault'), false)
for (let attempt = 0; attempt < 5; attempt++) assert.equal(await pin.verifyPin('000000'), false)
assert.ok(pin.retryAt() > env.clock.now)
await assert.rejects(pin.verifyPin('951753'), /Demasiados intentos/)
env.clock.now = pin.retryAt() + 1
assert.equal(await pin.verifyPin('951753'), true)
await pin.configurePin('off', '', '951753')
assert.equal(pin.isUnlocked('app'), true)
assert.equal(env.values.has(pin.PIN_KEY), false)

const { achievements } = env.read('src/lib/achievements.ts')
const badges = achievements(Array.from({ length: 10 }, () => ({ done: true })), [1, 2, 3], { count: 7, last: '2026-10-19' }, '2026-10-19')
assert.equal(badges.filter(badge => badge.earned).length, 4)
assert.equal(achievements([], [], { count: 100, last: '2026-09-01' }, '2026-10-19').find(badge => badge.id === 'week-streak').earned, false)
assert.ok(life.privacyInventory().every(row => !Object.hasOwn(row, 'value')))
const authOnly = runtime({ auth: true }).read('src/lib/backend.ts')
assert.equal(authOnly.authEnabled, true)
assert.equal(authOnly.backendEnabled, false)
assert.doesNotThrow(() => authOnly.requireAuth())
assert.throws(() => authOnly.requireBackend(), /Supabase está en pausa/)
assert.throws(() => runtime().read('src/lib/backend.ts').requireAuth(), /desactivado/)
console.log('Local feature checks passed: trash, retention, undo, versions, restore, Unicode sharing, independent authentication, paused backend, PIN hashing/lockout/scopes and badges.')
